CREATE TABLE IF NOT EXISTS users(id INTEGER PRIMARY KEY AUTOINCREMENT,email TEXT UNIQUE NOT NULL,salt TEXT NOT NULL,hash TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,user_id INTEGER NOT NULL,exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS records(user_id INTEGER NOT NULL,app TEXT NOT NULL,k TEXT NOT NULL,v TEXT,t INTEGER NOT NULL,deleted INTEGER DEFAULT 0,PRIMARY KEY(user_id,app,k));
CREATE INDEX IF NOT EXISTS rec_t ON records(user_id,app,t);
CREATE TABLE IF NOT EXISTS attempts(key TEXT NOT NULL,ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS att_k ON attempts(key,ts);
